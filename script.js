let currentLanguage=localStorage.getItem("language")||"te";

function applyLanguage(){
 const t=translations[currentLanguage];
 document.documentElement.lang=currentLanguage;
 document.querySelectorAll("[data-i18n]").forEach(el=>{
   const key=el.getAttribute("data-i18n");
   if(t[key]!==undefined) el.textContent=t[key];
 });
 document.getElementById("languageBtn").textContent=currentLanguage==="te"?"English":"తెలుగు";
 updateWhatsAppLinks();
}

function updateWhatsAppLinks(){
 const base="https://wa.me/919989803134?text=";
 const t=translations[currentLanguage];
 document.getElementById("heroWhatsapp").href=base+encodeURIComponent(t.messages.general);
 document.getElementById("ctaWhatsapp").href=base+encodeURIComponent(t.messages.general);
 document.getElementById("contactWhatsapp").href=base+encodeURIComponent(t.messages.general);
 document.getElementById("floatingWhatsapp").href=base+encodeURIComponent(t.messages.general);
 document.querySelectorAll(".service-whatsapp").forEach(link=>{
   link.href=base+encodeURIComponent(t.messages[link.dataset.service]);
 });
}

